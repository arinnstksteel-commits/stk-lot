// คำยาวที่อาจอยู่ปนกับข้อความอื่นในบรรทัดเดียว (แทนที่บางส่วน)
// ใช้เฉพาะคำยาว ≥ 5 ตัวอักษร เพื่อไม่ให้ไปแปลชื่อสินค้า
const PHRASES = Object.keys(MY).filter((k) => k.length >= 5 && /[฀-๿]/.test(k)).sort((a, b) => b.length - a.length);

const UNIT = { 'แผ่น': 'ချပ်', 'เส้น': 'ချောင်း', 'ชิ้น': 'ခု', 'ตัว': 'ခု', 'ท่อน': 'ပိုင်း', 'อัน': 'ခု', 'กก.': 'ကီလို' };

// รูปแบบที่มีตัวเลข/ข้อมูลแทรก
const PATTERNS = [
  [/(\d[\d,.]*) (แผ่น|เส้น|ชิ้น|ตัว|ท่อน|อัน|กก\.)/g, (_, n, u) => `${n} ${UNIT[u]}`],
  [/คงเหลือ /g, () => 'လက်ကျန် '],
  [/เลยกำหนด (\d+) วัน/g, (_, n) => `ရက်ကျော် ${n} ရက်`],
  [/ตัดโดย /g, () => 'ထုတ်သူ '],
  [/พิมพ์แล้ว /g, () => 'ပုံနှိပ်ပြီး '],
  [/รับคืน (\d)/g, (_, d) => `ပြန်လက်ခံ ${d}`],
  [/(^|[\s·])รับ (\d)/g, (_, p, d) => `${p}လက်ခံ ${d}`],
  [/(^|[\s·])สั่ง (\d)/g, (_, p, d) => `${p}မှာ ${d}`],
  [/(^|[\s·])ส่ง (\d)/g, (_, p, d) => `${p}ပို့ ${d}`],
  [/สร้าง (\d)/g, (_, d) => `ပြုလုပ် ${d}`],
  [/ส่งไป /g, () => 'ပို့ - '],
  [/กำหนดรับ /g, () => 'ပြန်ရမည့်ရက် '],
  [/ของลูกค้า /g, () => 'ဖောက်သည် '],
  [/ลัง (\d+)/g, (_, n) => `သေတ္တာ ${n}`],
  [/มัด (\d+)/g, (_, n) => `စည်း ${n}`],
  [/(\d+) รายการ/g, (_, n) => `${n} ခု`],
  [/(^|[\s·(])บิล /g, (_, p) => `${p}ဘောက်ချာ `],
  [/รับเข้า/g, () => 'အဝင်'],
];

export function tr(text) {
  if (getLang() !== 'my' || text == null) return text;
  const s = String(text);
  const trimmed = s.trim();
  if (!trimmed || !/[฀-๿]/.test(trimmed)) return s;
  if (MY[trimmed]) return s.replace(trimmed, MY[trimmed]);
  let out = s;
  for (const [re, fn] of PATTERNS) out = out.replace(re, fn);
  for (const p of PHRASES) if (out.includes(p)) out = out.split(p).join(MY[p]);
  return out;
}

// แปลข้อความทั้งหมดบนจอ + คอยแปลข้อความใหม่ที่ขึ้นมาเรื่อยๆ
function translateTree(root) {
  if (root.nodeType === Node.TEXT_NODE) {
    const v = tr(root.nodeValue);
    if (v !== root.nodeValue) root.nodeValue = v;
    return;
  }
  if (root.nodeType !== Node.ELEMENT_NODE) return;
  if (root.closest?.('[data-notr]')) return;
  for (const a of ['placeholder', 'aria-label', 'title', 'alt']) {
    const v = root.getAttribute?.(a);
    if (v) { const t = tr(v); if (t !== v) root.setAttribute(a, t); }
  }
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT | NodeFilter.SHOW_ELEMENT, {
    acceptNode: (n) => (n.nodeType === 1 && (n.tagName === 'SCRIPT' || n.tagName === 'STYLE' || n.hasAttribute('data-notr'))) ? NodeFilter.FILTER_REJECT : NodeFilter.FILTER_ACCEPT,
  });
  let n;
  while ((n = walker.nextNode())) {
    if (n.nodeType === 3) { const v = tr(n.nodeValue); if (v !== n.nodeValue) n.nodeValue = v; }
    else for (const a of ['placeholder', 'aria-label', 'title', 'alt']) {
      const v = n.getAttribute(a);
      if (v) { const t = tr(v); if (t !== v) n.setAttribute(a, t); }
    }
  }
}

export function initI18n() {
  const lang = getLang();
  document.documentElement.lang = lang;
  if (lang !== 'my') return;
  translateTree(document.body);
  new MutationObserver((muts) => {
    for (const m of muts) {
      if (m.type === 'characterData') translateTree(m.target);
      else m.addedNodes.forEach(translateTree);
    }
  }).observe(document.body, { childList: true, subtree: true, characterData: true });
  // กล่องยืนยัน / ถามของเบราว์เซอร์
  const c = window.confirm.bind(window); window.confirm = (msg) => c(tr(msg));
  const p = window.prompt.bind(window); window.prompt = (msg, d) => p(tr(msg), d);
}

